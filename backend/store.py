"""Database-backed account/profile store (SQLite locally, PostgreSQL on Render)."""

import json
import sqlite3
import time
from contextlib import contextmanager
from pathlib import Path

from matching import db as matching_db
from .security import token_digest

SCHEMA = Path(__file__).resolve().parents[1] / "matching" / "schema.sql"


class DuplicateUsername(Exception):
    pass


class Store:
    def __init__(self, database: Path | str):
        self.database = str(database)
        self.is_postgres = self.database.startswith(("postgres://", "postgresql://"))

    @contextmanager
    def connection(self):
        if self.is_postgres:
            import psycopg
            from psycopg.rows import dict_row
            with psycopg.connect(self.database, row_factory=dict_row) as conn:
                yield conn
            return

        conn = sqlite3.connect(self.database, timeout=10)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        try:
            with conn:
                yield conn
        finally:
            conn.close()

    def initialise(self):
        if self.is_postgres:
            self._initialise_postgres()
            return
        path = Path(self.database).expanduser().resolve()
        path.parent.mkdir(parents=True, exist_ok=True)
        with self.connection() as conn:
            tables = {r["name"] for r in conn.execute("SELECT name FROM sqlite_master WHERE type = 'table'")}
            existing = tables & {"accounts", "profiles"}
            if not existing:
                conn.executescript(SCHEMA.read_text(encoding="utf-8"))
            elif existing != {"accounts", "profiles"}:
                raise RuntimeError("Database has an incomplete matching schema; use a complete database or a new DB_PATH.")
            conn.executescript("""
                CREATE TABLE IF NOT EXISTS auth_sessions (
                    token_hash TEXT PRIMARY KEY,
                    account_id INTEGER NOT NULL,
                    expires_at INTEGER NOT NULL,
                    FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
                );
                CREATE INDEX IF NOT EXISTS auth_sessions_expiry ON auth_sessions(expires_at);
            """)

    def _initialise_postgres(self):
        schema = """
        CREATE TABLE IF NOT EXISTS accounts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS accounts_username_lower ON accounts (LOWER(username));
        CREATE TABLE IF NOT EXISTS profiles (
            account_id BIGINT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
            display_name TEXT NOT NULL,
            contact_info TEXT,
            city TEXT,
            preferred_role TEXT,
            languages TEXT,
            in_team INTEGER NOT NULL DEFAULT 0,
            updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
        );
        CREATE TABLE IF NOT EXISTS auth_sessions (
            token_hash TEXT PRIMARY KEY,
            account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
            expires_at BIGINT NOT NULL
        );
        CREATE INDEX IF NOT EXISTS auth_sessions_expiry ON auth_sessions(expires_at);
        """
        seed_sql = (SCHEMA.parent / "seed.sql").read_text(encoding="utf-8")
        with self.connection() as conn:
            for statement in schema.split(";"):
                if statement.strip():
                    conn.execute(statement)
            counts = conn.execute("SELECT COUNT(*) AS n FROM accounts").fetchone()
            if counts["n"] == 0:
                # The fixture file contains two INSERT statements; execute each
                # separately for compatibility with psycopg's prepared mode.
                for statement in seed_sql.split(";"):
                    if statement.strip():
                        conn.execute(statement)
                conn.execute("""
                    SELECT setval(pg_get_serial_sequence('accounts', 'id'),
                                  GREATEST((SELECT COALESCE(MAX(id), 1) FROM accounts), 1),
                                  EXISTS (SELECT 1 FROM accounts))
                """)

    def create_account(self, username: str, password_hash: str):
        try:
            with self.connection() as conn:
                if self.is_postgres:
                    found = conn.execute("SELECT id FROM accounts WHERE LOWER(username) = LOWER(%s)", (username,)).fetchone()
                    if found:
                        raise DuplicateUsername
                    row = conn.execute(
                        "INSERT INTO accounts (username, password_hash) VALUES (%s, %s) RETURNING id",
                        (username, password_hash),
                    ).fetchone()
                    return {"id": row["id"], "username": username}
                if conn.execute("SELECT id FROM accounts WHERE username = ? COLLATE NOCASE", (username,)).fetchone():
                    raise DuplicateUsername
                cursor = conn.execute("INSERT INTO accounts (username, password_hash) VALUES (?, ?)", (username, password_hash))
                return {"id": cursor.lastrowid, "username": username}
        except sqlite3.IntegrityError as exc:
            raise DuplicateUsername from exc
        except Exception as exc:
            if self.is_postgres:
                try:
                    from psycopg.errors import UniqueViolation
                    if isinstance(exc, UniqueViolation):
                        raise DuplicateUsername from exc
                except ImportError:
                    pass
            raise

    def _execute(self, conn, sql, params=()):
        return conn.execute(sql.replace("?", "%s") if self.is_postgres else sql, params)

    def account_for_login(self, username: str):
        with self.connection() as conn:
            row = self._execute(conn,
                "SELECT id, username, password_hash FROM accounts WHERE username = ? COLLATE NOCASE" if not self.is_postgres
                else "SELECT id, username, password_hash FROM accounts WHERE LOWER(username) = LOWER(?)",
                (username,)).fetchone()
            return dict(row) if row else None

    def create_session(self, account_id: int, token: str, ttl: int):
        now = int(time.time())
        with self.connection() as conn:
            self._execute(conn, "DELETE FROM auth_sessions WHERE expires_at <= ?", (now,))
            self._execute(conn, "INSERT INTO auth_sessions (token_hash, account_id, expires_at) VALUES (?, ?, ?)",
                          (token_digest(token), account_id, now + ttl))

    def session_account(self, token: str):
        with self.connection() as conn:
            row = self._execute(conn, """
                SELECT a.id, a.username FROM accounts AS a
                JOIN auth_sessions AS s ON s.account_id = a.id
                WHERE s.token_hash = ? AND s.expires_at > ?
            """, (token_digest(token), int(time.time()))).fetchone()
            return dict(row) if row else None

    def revoke_session(self, token: str):
        with self.connection() as conn:
            self._execute(conn, "DELETE FROM auth_sessions WHERE token_hash = ?", (token_digest(token),))

    def load_profile(self, account_id: int):
        with self.connection() as conn:
            row = self._execute(conn, "SELECT updated_at FROM profiles WHERE account_id = ?", (account_id,)).fetchone()
            if not row:
                return None
            profile = matching_db.load_profile(conn, account_id)
            return {**profile, "updated_at": str(row["updated_at"])}

    def save_profile(self, account_id: int, values: dict):
        with self.connection() as conn:
            sql = """
                INSERT INTO profiles (account_id, display_name, contact_info, city, preferred_role, languages)
                VALUES (?, ?, ?, ?, ?, ?)
                ON CONFLICT(account_id) DO UPDATE SET
                    display_name = excluded.display_name,
                    contact_info = excluded.contact_info,
                    city = excluded.city,
                    preferred_role = excluded.preferred_role,
                    languages = excluded.languages,
                    updated_at = CURRENT_TIMESTAMP
            """
            if self.is_postgres:
                sql = sql.replace("?", "%s").replace("updated_at = CURRENT_TIMESTAMP", "updated_at = CURRENT_TIMESTAMP::text")
            conn.execute(sql, (account_id, values["display_name"], values.get("contact_info"), values["city"],
                               values["preferred_role"], json.dumps(values["languages"], ensure_ascii=False)))
            profile = matching_db.load_profile(conn, account_id)
            updated = self._execute(conn, "SELECT updated_at FROM profiles WHERE account_id = ?", (account_id,)).fetchone()
            return {**profile, "updated_at": str(updated["updated_at"])}
